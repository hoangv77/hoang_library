import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import path from 'node:path';
import { tmpdir } from 'node:os';
import { createServer } from 'node:http';
import { createActiveStore } from '../scripts/active-store';
import { createLocalEditingMiddleware } from '../scripts/local-editing';
import { books } from '../src/data/books';
import { screen } from '../src/data/screen';
import { albums, tracks } from '../src/data/music';
import { emptyActive, validateCurrentlyActive, validateCurrentSelection, safePageImage } from '../src/lib/currentlyActive';

const collections = { books, screen, albums, tracks };
test('current selections validate membership, edition pages, episode ownership and track ownership', () => {
  const book = { ...books[0], editionPageCount: 100 };
  for (const pageNumber of [-1, 0, 1.5, 101, NaN]) assert.throws(() => validateCurrentSelection('reading', { bookId: book.id, pageNumber }, { ...collections, books: [book] }));
  assert.deepEqual(validateCurrentSelection('reading', { bookId: book.id, pageNumber: 100 }, { ...collections, books: [book] }), { bookId: book.id, pageNumber: 100 });
  for (const pageImage of ['../private.png', '/page-images/../../secret.png', 'https://example.com/page.png']) assert.equal(safePageImage(pageImage), false);
  assert.equal(safePageImage('/page-images/reading-12.webp'), true);
  assert.throws(() => validateCurrentSelection('reading', { bookId: book.id, pageImage: '/page-images/reading-12.webp' }, { ...collections, books: [book] }), /no longer supported/);
  const legacy = { ...emptyActive, reading: { bookId: book.id, pageImage: '/page-images/reading-12.webp' } };
  assert.deepEqual(validateCurrentlyActive(legacy), legacy);
  assert.throws(() => validateCurrentSelection('reading', { bookId: 'absent' }, collections));
  const series = screen.find(item => item.type === 'series')!, movie = screen.find(item => item.type === 'movie')!;
  assert.throws(() => validateCurrentSelection('watching', { screenId: movie.id, seasonNumber: 1 }, collections));
  assert.throws(() => validateCurrentSelection('watching', { screenId: series.id, seasonNumber: -1 }, collections));
  assert.throws(() => validateCurrentSelection('watching', { screenId: series.id, seasonNumber: 1, episodeNumber: 1 }, collections));
  const selection = { screenId: series.id, seasonNumber: 1, episodeNumber: 1 };
  assert.deepEqual(validateCurrentSelection('watching', selection, { ...collections, episodes: [{ ...selection, title: 'Episode', description: '' }] }), selection);
  assert.throws(() => validateCurrentSelection('playing', { albumId: albums[0].id, trackId: tracks.find(track => track.albumId !== albums[0].id)!.id }, collections));
  assert.deepEqual(validateCurrentSelection('playing', { albumId: albums[0].id }, collections), { albumId: albums[0].id });
  const orphan = { ...emptyActive, playing: { albumId: 'missing-after-import', trackId: 'missing-track' } };
  assert.deepEqual(validateCurrentlyActive(orphan), orphan);
});
test('serialized current selection writes preserve all categories, replacements, stable references and restarts', async t => {
  const root = await mkdtemp(path.join(tmpdir(), 'archive-active-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  await mkdir(path.join(root, 'src/data'), { recursive: true });
  const store = createActiveStore(root, collections);
  await Promise.all([store.save('reading', { bookId: books[0].id }), store.save('watching', { screenId: screen[0].id }), store.save('playing', { albumId: albums[0].id })]);
  const expected = { reading: { bookId: books[0].id }, watching: { screenId: screen[0].id }, playing: { albumId: albums[0].id } };
  assert.deepEqual((await store.read()).active, expected);
  assert.deepEqual((await createActiveStore(root, { ...collections, books: [...books].reverse(), albums: [] }).read()).active, expected);
  await store.save('reading', { bookId: books[1].id });
  assert.equal((await store.read()).active.reading?.bookId, books[1].id);
  await store.save('playing', null); assert.equal((await store.read()).active.playing, null);
  assert.equal((await store.read()).active.watching?.screenId, screen[0].id);
  const filename = path.join(root, 'src/data/currently-active.json');
  await writeFile(filename, '{broken'); await assert.rejects(store.save('playing', null)); assert.equal(await readFile(filename, 'utf8'), '{broken');
});
test('current selection HTTP writes use the existing local CSRF boundary and persist without touching overrides', async t => {
  const root = await mkdtemp(path.join(tmpdir(), 'archive-active-http-'));
  await mkdir(path.join(root, 'src/data'), { recursive: true });
  await writeFile(path.join(root, 'src/data/personal-overrides.json'), '[]\n');
  const middleware = createLocalEditingMiddleware(root);
  const server = createServer((request, response) => middleware(request, response, () => { response.statusCode = 404; response.end(); }));
  await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
  const address = server.address(); assert.ok(address && typeof address !== 'string');
  const base = `http://127.0.0.1:${address.port}`;
  t.after(async () => { server.closeAllConnections(); await new Promise<void>(resolve => server.close(() => resolve())); await rm(root, { recursive: true, force: true }); });
  const endpoint = base + '/__archive/currently-active';
  const { token } = await (await fetch(endpoint)).json();
  const payload = { category: 'reading', selection: { bookId: books[0].id, pageNumber: 1 } };
  const post = (headers: Record<string, string>, body: unknown = payload) => fetch(endpoint, { method: 'POST', headers: { 'Content-Type': 'application/json', ...headers }, body: JSON.stringify(body) });
  assert.equal((await post({})).status, 403);
  assert.equal((await post({ 'X-Archive-Token': token, Origin: 'https://foreign.test' })).status, 403);
  assert.equal((await post({ 'X-Archive-Token': token })).status, 200);
  assert.deepEqual((await (await fetch(endpoint)).json()).active.reading, payload.selection);
  assert.equal((await post({ 'X-Archive-Token': token }, { category: 'playing', selection: { albumId: 'unknown' } })).status, 400);
  assert.equal(await readFile(path.join(root, 'src/data/personal-overrides.json'), 'utf8'), '[]\n');
});
