test('album membership HTTP operations require same-origin local CSRF and persist manual albums', async t => {
  const { root } = await fixture(t);
  await writeFile(path.join(root, 'src/data/personal-overrides.json'), '[]\n');
  await writeFile(path.join(root, 'src/data/currently-active.json'), JSON.stringify(emptyActive));
  const middleware = createLocalEditingMiddleware(root);
  const server = createServer((request, response) => middleware(request, response, () => { response.statusCode = 404; response.end(); }));
  await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
  const address = server.address(); assert.ok(address && typeof address !== 'string');
  const base = `http://127.0.0.1:${address.port}`, endpoint = base + '/__archive/music-membership';
  t.after(async () => { server.closeAllConnections(); await new Promise<void>(resolve => server.close(() => resolve())); });
  const { token } = await (await fetch(endpoint)).json();
  const post = (body: unknown, headers: Record<string, string> = {}) => fetch(endpoint, { method: 'POST', headers: { 'Content-Type': 'application/json', ...headers }, body: JSON.stringify(body) });
  const addition = { action: 'add', title: 'HTTP record', artist: 'HTTP Artist', trackTitles: ['Track one'] };
  assert.equal((await post(addition)).status, 403);
  assert.equal((await post(addition, { 'X-Archive-Token': token, Origin: 'https://foreign.test' })).status, 403);
  const added = await post(addition, { 'X-Archive-Token': token }); assert.equal(added.status, 200);
  const state = await added.json(), id = state.manual[0].album.id;
  assert.equal((await post(addition, { 'X-Archive-Token': token })).status, 400);
  assert.equal((await post({ action: 'remove', id }, { 'X-Archive-Token': token })).status, 200);
  assert.equal((await (await fetch(endpoint)).json()).state.excluded[0].album.id, id);
  assert.equal((await post({ action: 'restore', id }, { 'X-Archive-Token': token })).status, 200);
  assert.equal((await (await fetch(endpoint)).json()).state.excluded.length, 0);
  assert.equal(await readFile(path.join(root, 'src/data/personal-overrides.json'), 'utf8'), '[]\n');
});
