async function fixture(t: { after: (callback: () => Promise<void>) => void }, imported = { albums, tracks }) {
  const root = await mkdtemp(path.join(tmpdir(), 'archive-membership-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  await mkdir(path.join(root, 'src/data'), { recursive: true });
  let music: ReturnType<typeof createMusicStore>;
  const active = createActiveStore(root, { books, screen, ...imported }, () => music.collections());
  music = createMusicStore(root, active, imported);
  return { root, music, active };
}
test('manual additions bypass the threshold, reject duplicates and persist after server restart and reimport', async t => {
  const { root, music, active } = await fixture(t);
  const original = await readFile('src/data/music.ts', 'utf8');
  const state = await music.add({ title: 'A quiet record', artist: 'A new artist', year: 2001, trackTitles: ['First song', 'Second song'] });
  const record = state.manual[0];
  assert.equal(record.album.observedScrobbles, 0); assert.equal(record.album.tracklistSource, 'provided');
  assert.ok((await music.collections()).albums.some(album => album.id === record.album.id));
  await assert.rejects(music.add({ title: 'A QUIET RECORD (Deluxe Edition)', artist: 'A New Artist' }), /already in your collection/);
  await assert.rejects(music.add({ title: albums[0].title, artist: albums[0].artist }), /already in your collection/);
  await assert.rejects(music.add({ title: '', artist: 'Artist' }), /valid album title/);
  const restarted = createMusicStore(root, active, { albums: [], tracks: [] });
  assert.deepEqual((await restarted.read()).manual, state.manual);
  assert.equal((await restarted.collections()).albums[0].id, record.album.id);
  assert.equal(await readFile('src/data/music.ts', 'utf8'), original);
  await active.save('playing', { albumId: record.album.id, trackId: record.tracks[0].id });
  assert.equal((await active.read()).active.playing?.albumId, record.album.id);
});
test('removal survives imports, clears only the matching playing selection and restores prior personalization', async t => {
  const { root, music, active } = await fixture(t);
  const album = albums[0], track = tracks.find(track => track.albumId === album.id)!;
  const override: MediaOverride = { media_type: 'album', media_id: album.id, is_favorite: true, personal_comment: 'Keep this memory', rating_is_overridden: true, personal_rating: 5 };
  const overrideFile = path.join(root, 'src/data/personal-overrides.json');
  await writeFile(overrideFile, JSON.stringify([override]));
  await active.save('reading', { bookId: books[0].id });
  await active.save('watching', { screenId: screen[0].id });
  await active.save('playing', { albumId: album.id, trackId: track.id });
  await music.remove(album.id);
  assert.equal((await active.read()).active.playing, null);
  assert.equal((await active.read()).active.reading?.bookId, books[0].id);
  assert.equal((await active.read()).active.watching?.screenId, screen[0].id);
  assert.ok(!(await music.collections()).albums.some(item => item.id === album.id));
  const restarted = createMusicStore(root, active, { albums: [...albums].reverse(), tracks });
  assert.ok(!(await restarted.collections()).albums.some(item => item.id === album.id));
  await assert.rejects(active.save('playing', { albumId: album.id }), /not in the current collection/);
  await restarted.restore(album.id);
  const restored = mergeAlbums((await restarted.collections()).albums, [override]).find(item => item.id === album.id)!;
  assert.equal(restored.isFavorite, true); assert.equal(restored.personalRating, 5); assert.equal(restored.personalComment, override.personal_comment);
  assert.equal(await readFile(overrideFile, 'utf8'), JSON.stringify([override]));
  assert.equal((await active.read()).active.playing, null);
});
test('manual removals and restoration survive imports even when an automatic album disappears', async t => {
  const { root, music, active } = await fixture(t);
  let state = await music.add({ title: 'Hand-added', artist: 'Artist' });
  const id = state.manual[0].album.id;
  await music.remove(id);
  const restarted = createMusicStore(root, active);
  assert.ok(!(await restarted.collections()).albums.some(item => item.id === id));
  await restarted.restore(id);
  assert.ok((await restarted.collections()).albums.some(item => item.id === id));
  await restarted.remove(albums[0].id);
  const later = createMusicStore(root, active, { albums: [], tracks: [] });
  await later.restore(albums[0].id);
  assert.ok((await later.collections()).albums.some(item => item.id === albums[0].id));
  state = await later.read(); assert.ok(state.manual.some(item => item.album.id === albums[0].id));
});
test('custom metadata is preserved when its album becomes eligible for automatic import', () => {
  const album = { ...manualAlbum('New record', 'Artist'), year: 2000, tracklistSource: 'provided' as const };
  const track = { ...manualTrack(album.id, 'A song'), trackNumber: 1 };
  album.trackIds = [track.id];
  const imported = { ...album, year: 2002, observedScrobbles: 70, lastPlayedAt: '2026-01-01T00:00:00.000Z' };
  const merged = mergeMusicMembership([imported], [{ ...track, observedScrobbles: 70 }], { manual: [{ album, tracks: [track] }], excluded: [] });
  assert.equal(merged.albums.length, 1); assert.equal(merged.albums[0].year, 2000);
  assert.equal(merged.albums[0].observedScrobbles, 70); assert.equal(merged.tracks[0].observedScrobbles, 70);
  assert.throws(() => validateMembership({ manual: [{ album, tracks: [] }], excluded: [] }), /track references/);
});
test('verified metadata aliases reconcile imports with manual IDs and persistent exclusions', () => {
  const album = { ...manualAlbum('Home', 'Artist alias'), musicbrainzId: 'shared-group' };
  const track = manualTrack(album.id, 'A song'); album.trackIds = [track.id];
  const imported = { ...manualAlbum('Home', 'Artist canonical'), musicbrainzId: 'shared-group', observedScrobbles: 70 };
  const observed = { ...manualTrack(imported.id, 'A song'), observedScrobbles: 70 }; imported.trackIds = [observed.id];
  const merged = mergeMusicMembership([imported], [observed], { manual: [{ album, tracks: [track] }], excluded: [] });
  assert.equal(merged.albums.length, 1); assert.equal(merged.albums[0].id, album.id);
  assert.equal(merged.tracks.length, 1); assert.equal(merged.tracks[0].id, track.id); assert.equal(merged.tracks[0].observedScrobbles, 70);
  assert.equal(mergeMusicMembership([imported], [observed], { manual: [], excluded: [{ album, tracks: [track] }] }).albums.length, 0);
});
