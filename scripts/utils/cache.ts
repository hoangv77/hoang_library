import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

export const offline = process.argv.includes('--offline');
const last = new Map<string, number>();
const pause = (ms: number) => new Promise(r => setTimeout(r, ms));
export async function loadEnv() {
  try {
    const content = await readFile('.env', 'utf8');
    for (const line of content.split(/\r?\n/)) {
      const match = line.match(/^([A-Z_]+)=(.*)$/);
      if (match && !process.env[match[1]]) process.env[match[1]] = match[2].replace(/^(['"])(.*)\1$/, '$2');
    }
  } catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
}

export async function request(url: string, headers: Record<string, string> = {}, binary = false): Promise<any> {
  const key = createHash('sha256').update(url).digest('hex');
  const path = resolve('.cache', key + (binary ? '.image' : '.json'));
  try { const data = await readFile(path); return binary ? data : JSON.parse(data.toString()); } catch { /* cache miss */ }
  if (offline) return undefined;
  const host = new URL(url).host;
  const delay = host.includes('openlibrary') || host.includes('musicbrainz') ? 1100 : 120;
  for (let attempt = 0; attempt < 3; attempt++) {
    await pause(Math.max(0, (last.get(host) ?? 0) + delay - Date.now()));
    last.set(host, Date.now());
    try {
      const response = await fetch(url, { headers, signal: AbortSignal.timeout(18000) });
      if (response.status === 404) return undefined;
      if (!response.ok) {
        if (response.status !== 429 && response.status < 500) return undefined;
        const retry = Number(response.headers.get('retry-after'));
        await pause(Number.isFinite(retry) && retry > 0 ? Math.min(retry * 1000, 30000) : 800 * 2 ** attempt);
        continue;
      }
      const bytes = Buffer.from(await response.arrayBuffer());
      if (binary && bytes.length < 200) return undefined;
      const result = binary ? bytes : JSON.parse(bytes.toString());
      await mkdir('.cache', { recursive: true }); await writeFile(path, bytes);
      return result;
    } catch { await pause(800 * 2 ** attempt); }
  }
  return undefined;
}

export async function writeData(path: string, exportName: string, data: unknown) {
  const existing = await readFile(path, 'utf8');
  const typeDefinition = existing.slice(0, existing.indexOf('// '));
  await writeFile(path, `${typeDefinition}// Generated by the import pipeline. Do not hand-edit collection records.\nexport const ${exportName}: ${exportName === 'books' ? 'Book' : 'ScreenTitle'}[] = ${JSON.stringify(data, null, 2)};\n`);
}
export async function summary(name: string, report: unknown) {
  await mkdir('.cache', { recursive: true });
  await writeFile(`.cache/${name}-summary.json`, JSON.stringify(report, null, 2) + '\n');
  console.log(JSON.stringify(report, null, 2));
}
